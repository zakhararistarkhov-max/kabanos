package postgres

import (
	"context"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
)

// Querier is the subset of pgx behaviour shared by *pgxpool.Pool and pgx.Tx.
// Repository methods accept a Querier so the same code path works for
// standalone queries and for queries that must run inside a caller's
// transaction (e.g. write-alongside-outbox).
type Querier interface {
	Query(ctx context.Context, sql string, args ...any) (pgx.Rows, error)
	QueryRow(ctx context.Context, sql string, args ...any) pgx.Row
	Exec(ctx context.Context, sql string, args ...any) (pgconn.CommandTag, error)
}
